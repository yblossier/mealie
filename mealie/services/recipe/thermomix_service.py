import json
import time
from datetime import UTC, datetime
from pathlib import Path
from uuid import UUID

from mealie.repos.repository_factory import AllRepositories
from mealie.schema.openai.thermomix import OpenAIThermomixView
from mealie.schema.recipe.recipe import RecipeOut
from mealie.schema.recipe.recipe_step import RecipeStep
from mealie.schema.recipe.recipe_thermomix import (
    RecipeThermomixView,
    ThermomixLogEntry,
    ThermomixLogStatus,
    ThermomixStep,
)
from mealie.services._base_service import BaseService
from mealie.services.openai import OpenAINotEnabledException, OpenAIService
from mealie.services.recipe.thermomix_settings import complete_step

GENERATE_THERMOMIX_STEPS_PROMPT = "recipes.generate-thermomix-steps"
THERMOMIX_VIEW_FILE = "thermomix.json"
THERMOMIX_LOG_FILE = "thermomix-log.json"
MAX_LOG_ENTRIES = 20


def _positive(seconds: int | None) -> int | None:
    return seconds if seconds and seconds > 0 else None


class ThermomixService(BaseService):
    """
    Keeps an alternative view of a recipe's steps adapted for the Thermomix, generated by the AI provider.
    The view lives next to the recipe's images and assets, so it follows the recipe when it's duplicated,
    backed up or deleted, without touching the recipe itself.
    """

    def __init__(self, repos: AllRepositories) -> None:
        self.repos = repos
        super().__init__()

    @staticmethod
    def _path(recipe: RecipeOut) -> Path:
        return RecipeOut.directory_from_id(recipe.id) / THERMOMIX_VIEW_FILE

    def get(self, recipe: RecipeOut) -> RecipeThermomixView | None:
        path = self._path(recipe)
        if not path.exists():
            return None
        try:
            view = RecipeThermomixView.model_validate_json(path.read_text(encoding="utf-8"))
            # views generated before the settings were read from the text still hold placeholders
            view.steps = [complete_step(step) for step in view.steps]
            # views generated before the step titles were kept take them from their original steps
            summaries = {step.id: step.summary for step in recipe.recipe_instructions if step.id and step.summary}
            for step in view.steps:
                if not step.summary:
                    step.summary = next((summaries[i] for i in step.source_step_ids if i in summaries), None)
            return view
        except Exception:
            self.logger.exception(f"Unable to read the Thermomix view of {recipe.slug}")
            return None

    def delete(self, recipe: RecipeOut) -> None:
        self._path(recipe).unlink(missing_ok=True)

    @staticmethod
    def _log_path(recipe: RecipeOut) -> Path:
        return RecipeOut.directory_from_id(recipe.id) / THERMOMIX_LOG_FILE

    def get_logs(self, recipe: RecipeOut) -> list[ThermomixLogEntry]:
        """The latest generation attempts, newest first"""
        path = self._log_path(recipe)
        if not path.exists():
            return []
        try:
            entries = json.loads(path.read_text(encoding="utf-8"))
            return [ThermomixLogEntry.model_validate(entry) for entry in entries]
        except Exception:
            self.logger.exception(f"Unable to read the Thermomix log of {recipe.slug}")
            return []

    def _add_log(self, recipe: RecipeOut, entry: ThermomixLogEntry) -> None:
        try:
            entries = [entry, *self.get_logs(recipe)][:MAX_LOG_ENTRIES]
            path = self._log_path(recipe)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(
                json.dumps([e.model_dump(mode="json") for e in entries], ensure_ascii=False), encoding="utf-8"
            )
        except Exception:
            self.logger.exception(f"Unable to write the Thermomix log of {recipe.slug}")

    def _save(self, recipe: RecipeOut, view: RecipeThermomixView) -> RecipeThermomixView:
        path = self._path(recipe)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(view.model_dump_json(), encoding="utf-8")
        return view

    @staticmethod
    def _source_steps(recipe: RecipeOut) -> list[tuple[RecipeStep, str | None]]:
        """The steps with text, each with the title of the section it belongs to"""
        steps: list[tuple[RecipeStep, str | None]] = []
        section: str | None = None
        for step in recipe.recipe_instructions:
            if step.title:
                section = step.title
            if step.text:
                steps.append((step, section))
        return steps

    @classmethod
    def _message(cls, recipe: RecipeOut) -> str:
        sources = cls._source_steps(recipe)
        numbers = {step.id: number for number, (step, _) in enumerate(sources, start=1) if step.id}
        tool_names = {tool.id: tool.name for tool in recipe.tools}
        return json.dumps(
            {
                "name": recipe.name,
                "yield": recipe.recipe_yield or None,
                "servings": recipe.recipe_servings or None,
                "ingredients": [
                    ingredient.display or ingredient.note
                    for ingredient in recipe.recipe_ingredient
                    if ingredient.display or ingredient.note
                ],
                "tools": [tool.name for tool in recipe.tools],
                "steps": [
                    {
                        "number": number,
                        "section": section,
                        "title": step.summary or None,
                        "text": step.text,
                        **{
                            key: value
                            for key, value in (
                                ("duration_seconds", step.duration_seconds),
                                ("cooking_seconds", step.cooking_seconds),
                                ("rest_seconds", step.rest_seconds),
                                ("cooling_seconds", step.cooling_seconds),
                            )
                            if value
                        },
                        **(
                            {"uses_steps": uses}
                            if (
                                uses := [
                                    numbers[ref.reference_id]
                                    for ref in step.step_references
                                    if ref.reference_id in numbers
                                ]
                            )
                            else {}
                        ),
                        **(
                            {"tools": linked}
                            if (
                                linked := [
                                    tool_names[ref.reference_id]
                                    for ref in step.tool_references
                                    if ref.reference_id in tool_names
                                ]
                            )
                            else {}
                        ),
                    }
                    for number, (step, section) in enumerate(sources, start=1)
                ],
            },
            ensure_ascii=False,
        )

    @classmethod
    def _to_view(cls, recipe: RecipeOut, response: OpenAIThermomixView, model: str | None) -> RecipeThermomixView:
        sources = cls._source_steps(recipe)
        tools_by_name = {tool.name.strip().casefold(): tool.id for tool in recipe.tools}
        steps: list[ThermomixStep] = []
        current_section: str | None = None
        for step in response.steps:
            if not step.text.strip():
                continue

            numbers = [number for number in step.source_steps if 0 < number <= len(sources)]
            source, section = sources[numbers[0] - 1] if numbers else (None, current_section)
            summary = (source.summary if source else None) or step.title or None
            # The AI gives the tool names; only the recipe tools can be linked, the accessory included
            tool_ids: list[UUID] = []
            for name in [*step.tools, step.accessory or ""]:
                tool_id = tools_by_name.get(name.strip().casefold())
                if tool_id and tool_id not in tool_ids:
                    tool_ids.append(tool_id)
            steps.append(
                complete_step(
                    ThermomixStep(
                        title=section if section and section != current_section else None,
                        summary=summary,
                        text=step.text,
                        time_seconds=step.time_seconds,
                        cooling_seconds=_positive(step.cooling_seconds),
                        cooking_seconds=_positive(step.cooking_seconds),
                        rest_seconds=_positive(step.rest_seconds),
                        temperature=step.temperature,
                        speed=step.speed,
                        reverse=bool(step.reverse),
                        accessory=step.accessory,
                        source_step_ids=[sources[number - 1][0].id for number in numbers if sources[number - 1][0].id],
                        tool_ids=tool_ids,
                        cautions=[caution.strip() for caution in step.cautions if caution.strip()],
                    )
                )
            )
            current_section = section

        return RecipeThermomixView(
            steps=steps,
            notes=[note for note in response.notes if note.strip()],
            model=model,
            created_at=datetime.now(UTC),
        )

    async def generate(self, recipe: RecipeOut, user: str | None = None) -> RecipeThermomixView:
        if not any(step.text for step in recipe.recipe_instructions):
            raise ValueError("The recipe has no steps to adapt")

        service = OpenAIService(self.repos)
        provider = service.default_provider
        if not provider:
            raise OpenAINotEnabledException()

        prompt = service.get_prompt(GENERATE_THERMOMIX_STEPS_PROMPT)
        message = self._message(recipe)
        prompt_chars = len(prompt) + len(message) + len(json.dumps(OpenAIThermomixView.model_json_schema()))
        entry = ThermomixLogEntry(
            created_at=datetime.now(UTC),
            status=ThermomixLogStatus.error,
            user=user,
            provider=provider.name,
            model=provider.model,
            timeout_seconds=provider.timeout,
            prompt_chars=prompt_chars,
            estimated_tokens=prompt_chars // 4,
            request=message,
        )
        self.logger.info(
            f"Generating the Thermomix view of {recipe.slug} with {provider.name} ({provider.model}),"
            f" about {entry.estimated_tokens} input tokens"
        )

        start = time.perf_counter()
        try:
            response = await service.get_response(prompt, message, response_schema=OpenAIThermomixView)
            entry.response = response.model_dump(mode="json") if response else None
            if not response or not response.steps:
                raise ValueError("The AI provider returned no steps")

            view = self._save(recipe, self._to_view(recipe, response, provider.model))
            entry.status = ThermomixLogStatus.success
            entry.steps_count = len(view.steps)
            return view
        except Exception as e:
            entry.error = f"{e.__class__.__name__}: {e}"
            raise
        finally:
            entry.duration_ms = round((time.perf_counter() - start) * 1000)
            self.logger.info(
                f"Thermomix view of {recipe.slug}: {entry.status} in {entry.duration_ms} ms"
                + (f" ({entry.error})" if entry.error else "")
            )
            self._add_log(recipe, entry)
